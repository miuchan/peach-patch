export async function GET(request:Request){
  const url=new URL(request.url),name=url.searchParams.get("name")??"";
  let asset=assets[name];
  if(!asset)return new Response("Rack component not found",{status:404});
  if(name==="Plug"){
    const color=url.searchParams.get("color")??"";
    if(/^#[0-9a-f]{6}$/i.test(color))asset=asset.replace('fill="#FFFFFF"',`fill="${color}"`);
  }
  return new Response(asset,{headers:{"Cache-Control":"public, max-age=31536000, immutable","Content-Type":"image/svg+xml; charset=utf-8"}});
}
