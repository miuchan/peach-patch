function drawGlyph(context: CanvasRenderingContext2D, character: string, x: number, y: number) {
  const glyph = GLYPHS[character] ?? GLYPHS[character.toUpperCase()] ?? GLYPHS[" "];
  const size = 2;
  const pitch = 2.7;
  glyph.forEach((row, rowIndex) => {
    for (let column = 0; column < row.length; column++) {
      if (row[column] === "1")
        context.fillRect(x + column * pitch, y + rowIndex * pitch, size, size);
    }
  });
}

export function RackVerticalLabel({
  text,
  maximumLength,
  x,
  y,
  width,
  height,
  scaleX,
}: {
  text: string;
  maximumLength: number;
  x: number;
  y: number;
  width: number;
  height: number;
  scaleX: number;
}) {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  useEffect(() => {
    const canvas = canvasRef.current;
    const context = canvas?.getContext("2d");
    if (!canvas || !context) return;
    context.clearRect(0, 0, width, height);
    context.fillStyle = "rgb(34,35,39)";
    context.beginPath();
    context.roundRect(0, 0, width, height, 3);
    context.fill();
    context.save();
    context.translate(width - 2, height - 5);
    context.rotate(-Math.PI / 2);
    context.fillStyle = "rgb(76,199,243)";
    [...text.slice(0, maximumLength)].forEach((character, index) =>
      drawGlyph(context, character, index * 13, -19),
    );
    context.restore();
  }, [height, maximumLength, text, width]);
  return (
    <canvas
      ref={canvasRef}
      role="img"
      aria-label={text}
      width={width}
      height={height}
      style={{
        position: "absolute",
        left: x * scaleX,
        top: y,
        width: width * scaleX,
        height,
        pointerEvents: "none",
      }}
    />
  );
}
