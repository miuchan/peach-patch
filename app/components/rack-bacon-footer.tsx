export function RackBaconFooter({ visual, scaleX }: { visual: BaconFooterVisual; scaleX: number }) {
  const [pressed, setPressed] = useState(false);
  const release = (event: PointerEvent<HTMLButtonElement>) => {
    setPressed(false);
    if (event.currentTarget.hasPointerCapture(event.pointerId))
      event.currentTarget.releasePointerCapture(event.pointerId);
  };

  return (
    <button
      type="button"
      className="pw-rack-bacon-footer"
      aria-label="Bacon Music logo"
      style={{
        position: "absolute",
        left: visual.x * scaleX,
        top: visual.y,
        width: visual.width * scaleX,
        height: visual.height,
        padding: 0,
        border: 0,
        background: "transparent",
        cursor: "pointer",
        touchAction: "none",
      }}
      onPointerDown={(event) => {
        if (event.button !== 0) return;
        event.preventDefault();
        event.stopPropagation();
        setPressed(true);
        event.currentTarget.setPointerCapture(event.pointerId);
      }}
      onPointerUp={release}
      onPointerCancel={release}
      onLostPointerCapture={() => setPressed(false)}
    >
      {pressed ? <LoveBaconSvg /> : <BaconSvg />}
    </button>
  );
}
